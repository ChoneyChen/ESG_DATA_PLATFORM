-- A concept definition can belong to several immutable dictionary releases.
-- dictionary_version on old definition rows remains its introduction version.
CREATE TABLE esg.dictionary_versions (
    release_order bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    dictionary_version text PRIMARY KEY,
    snapshot_digest char(64),
    snapshot jsonb,
    provenance text NOT NULL CHECK (provenance IN ('legacy_membership','versioned_snapshot')),
    sealed boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK ((snapshot_digest IS NULL AND snapshot IS NULL AND provenance='legacy_membership') OR
           (snapshot_digest IS NOT NULL AND snapshot IS NOT NULL AND provenance='versioned_snapshot'))
);
CREATE TABLE esg.dictionary_membership (
    dictionary_version text NOT NULL REFERENCES esg.dictionary_versions(dictionary_version),
    metric_id text NOT NULL,
    definition_version text NOT NULL,
    source_datapoint_id text NOT NULL,
    PRIMARY KEY (dictionary_version,metric_id),
    UNIQUE (dictionary_version,source_datapoint_id),
    FOREIGN KEY (metric_id,definition_version) REFERENCES esg.metric_definition_versions(metric_id,definition_version)
);
INSERT INTO esg.dictionary_versions(dictionary_version,provenance,created_at)
    SELECT dictionary_version,'legacy_membership',min(created_at)
    FROM esg.metric_definition_versions GROUP BY dictionary_version ORDER BY min(created_at),dictionary_version;
INSERT INTO esg.dictionary_membership(dictionary_version,metric_id,definition_version,source_datapoint_id)
    SELECT dictionary_version,metric_id,definition_version,source_datapoint_id FROM esg.metric_definition_versions;
UPDATE esg.dictionary_versions SET sealed=true;

CREATE FUNCTION esg.protect_dictionary_version() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP='DELETE' THEN RAISE EXCEPTION 'immutable dictionary snapshot'; END IF;
    IF OLD.sealed THEN
        -- One-time recovery of metadata missing in the old schema preserves
        -- the already frozen membership, introduction order and timestamps.
        IF OLD.provenance='legacy_membership' AND OLD.snapshot_digest IS NULL
           AND NEW.provenance='versioned_snapshot' AND NEW.snapshot_digest IS NOT NULL
           AND NEW.snapshot IS NOT NULL AND NEW.sealed
           AND NEW.dictionary_version=OLD.dictionary_version
           AND NEW.release_order=OLD.release_order AND NEW.created_at=OLD.created_at THEN
            RETURN NEW;
        END IF;
        RAISE EXCEPTION 'immutable dictionary snapshot';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER immutable_dictionary_version BEFORE UPDATE OR DELETE ON esg.dictionary_versions
    FOR EACH ROW EXECUTE FUNCTION esg.protect_dictionary_version();
CREATE FUNCTION esg.protect_dictionary_membership() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP<>'INSERT' THEN RAISE EXCEPTION 'immutable dictionary membership'; END IF;
    IF (SELECT sealed FROM esg.dictionary_versions WHERE dictionary_version=NEW.dictionary_version) THEN
        RAISE EXCEPTION 'immutable dictionary membership';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER immutable_dictionary_membership BEFORE INSERT OR UPDATE OR DELETE ON esg.dictionary_membership
    FOR EACH ROW EXECUTE FUNCTION esg.protect_dictionary_membership();
