-- Candidate facts and published observations have independent lifecycles.
-- Product-owned company registration remains outside this schema.
CREATE TABLE esg.metric_definition_versions (
    metric_id text NOT NULL,
    definition_version text NOT NULL,
    dictionary_version text NOT NULL,
    source_datapoint_id text NOT NULL,
    readiness text NOT NULL CHECK (readiness IN ('ready','planned')),
    definition jsonb NOT NULL,
    definition_digest char(64) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (metric_id,definition_version),
    UNIQUE (dictionary_version,source_datapoint_id)
);

CREATE TABLE esg.measurement_contexts (
    context_id uuid PRIMARY KEY,
    mapping_id uuid NOT NULL REFERENCES esg.disclosure_standard_mappings(disclosure_standard_mapping_id),
    revision integer NOT NULL CHECK (revision > 0),
    entity_ref text NOT NULL CHECK (length(trim(entity_ref)) > 0),
    period_start date NOT NULL,
    period_end date NOT NULL CHECK (period_end >= period_start),
    boundary_code text NOT NULL CHECK (length(trim(boundary_code)) > 0),
    value_role text NOT NULL CHECK (value_role IN ('actual','restated','context')),
    measurement_method text CHECK (measurement_method IS NULL OR length(trim(measurement_method)) > 0),
    dimensions jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(dimensions) = 'object'),
    reported_unit text,
    operator_ref text NOT NULL CHECK (length(trim(operator_ref)) > 0),
    reason text NOT NULL CHECK (length(trim(reason)) > 0),
    supersedes_observation_id uuid,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (mapping_id,revision)
);

CREATE TABLE esg.curated_observations (
    observation_id uuid PRIMARY KEY,
    metric_id text NOT NULL,
    definition_version text NOT NULL,
    identity_key char(64) NOT NULL,
    entity_ref text NOT NULL,
    period_start date NOT NULL,
    period_end date NOT NULL,
    boundary_code text NOT NULL,
    value_role text NOT NULL CHECK (value_role IN ('actual','restated','context')),
    measurement_method text,
    dimensions jsonb NOT NULL,
    canonical_unit text,
    numeric_value numeric,
    lower_bound numeric,
    upper_bound numeric,
    precision_qualifier text,
    statement text,
    comparison_eligibility text NOT NULL CHECK (comparison_eligibility IN ('comparable','conditional','not_comparable')),
    comparison_reasons jsonb NOT NULL DEFAULT '[]'::jsonb,
    normalization_rule_version text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (metric_id,definition_version) REFERENCES esg.metric_definition_versions(metric_id,definition_version),
    CHECK ((statement IS NOT NULL) <> (numeric_value IS NOT NULL OR lower_bound IS NOT NULL OR upper_bound IS NOT NULL)),
    CHECK (lower_bound IS NULL OR upper_bound IS NULL OR upper_bound >= lower_bound)
);
