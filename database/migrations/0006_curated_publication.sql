    context_id uuid NOT NULL REFERENCES esg.measurement_contexts(context_id),
    disclosure_id uuid NOT NULL REFERENCES esg.esg_disclosures(disclosure_id),
    mapping_id uuid NOT NULL REFERENCES esg.disclosure_standard_mappings(disclosure_standard_mapping_id),
    source_snapshot jsonb NOT NULL,
    PRIMARY KEY (observation_id,context_id)
);
CREATE TABLE esg.publication_states (
    mapping_id uuid PRIMARY KEY REFERENCES esg.disclosure_standard_mappings(disclosure_standard_mapping_id),
    fact_review_status text NOT NULL,
    mapping_review_status text NOT NULL,
    publication_status text NOT NULL CHECK (publication_status IN ('not_published','blocked','published','withdrawn','superseded')),
    reason_codes jsonb NOT NULL DEFAULT '[]'::jsonb,
    observation_id uuid REFERENCES esg.curated_observations(observation_id),
    last_evaluated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE esg.dataset_versions (
    dataset_version bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dictionary_version text NOT NULL,
    content_digest char(64) NOT NULL,
    sealed boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE esg.dataset_membership (
    dataset_version bigint NOT NULL REFERENCES esg.dataset_versions(dataset_version),
    observation_id uuid NOT NULL REFERENCES esg.curated_observations(observation_id),
    PRIMARY KEY (dataset_version,observation_id)
);
