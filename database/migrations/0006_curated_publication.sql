CREATE FUNCTION esg.reject_snapshot_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'immutable snapshot: %', TG_TABLE_NAME; END $$;
CREATE TRIGGER immutable_metric_definition BEFORE UPDATE OR DELETE ON esg.metric_definition_versions FOR EACH ROW EXECUTE FUNCTION esg.reject_snapshot_mutation();
CREATE TRIGGER immutable_measurement_context BEFORE UPDATE OR DELETE ON esg.measurement_contexts FOR EACH ROW EXECUTE FUNCTION esg.reject_snapshot_mutation();
CREATE TRIGGER immutable_curated_observation BEFORE UPDATE OR DELETE ON esg.curated_observations FOR EACH ROW EXECUTE FUNCTION esg.reject_snapshot_mutation();
CREATE TRIGGER immutable_observation_sources BEFORE UPDATE OR DELETE ON esg.observation_sources FOR EACH ROW EXECUTE FUNCTION esg.reject_snapshot_mutation();
CREATE FUNCTION esg.protect_dataset() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' OR OLD.sealed OR NEW.dataset_version <> OLD.dataset_version
       OR NEW.dictionary_version <> OLD.dictionary_version OR NEW.content_digest <> OLD.content_digest
       OR NEW.created_at <> OLD.created_at OR NOT NEW.sealed THEN
        RAISE EXCEPTION 'immutable dataset';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER immutable_dataset BEFORE UPDATE OR DELETE ON esg.dataset_versions FOR EACH ROW EXECUTE FUNCTION esg.protect_dataset();
CREATE FUNCTION esg.protect_dataset_membership() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP <> 'INSERT' THEN RAISE EXCEPTION 'immutable dataset membership'; END IF;
    IF (SELECT sealed FROM esg.dataset_versions WHERE dataset_version=NEW.dataset_version) THEN
        RAISE EXCEPTION 'sealed dataset membership';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER immutable_dataset_membership BEFORE INSERT OR UPDATE OR DELETE ON esg.dataset_membership FOR EACH ROW EXECUTE FUNCTION esg.protect_dataset_membership();
