def flag_label(flag: str) -> str:
    if flag.startswith("reassigned_from_"):
        return "已按条款定义从相近条款改归本项"
    if flag.startswith("boundary_model_"):
        return "模型与表头对主体范围的判断不一致"
    return FLAG_LABELS.get(flag, flag)
