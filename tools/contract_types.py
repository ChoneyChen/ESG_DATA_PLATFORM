"""Development-only JSON Schema to TypeScript renderer shared by module exporters."""
import json


def render(schema, prefix):
    if "$ref" in schema:
        return prefix + "_" + schema["$ref"].rsplit("/", 1)[-1]
    if "const" in schema:
        return json.dumps(schema["const"], ensure_ascii=False)
    if "enum" in schema:
        return " | ".join(json.dumps(v, ensure_ascii=False) for v in schema["enum"])
    for union in ("anyOf", "oneOf"):
        if union in schema:
            return (
                "(" + " | ".join(render(part, prefix) for part in schema[union]) + ")"
            )
    kind = schema.get("type")
    if kind == "null":
        return "null"
    if kind == "string":
        return "string"
    if kind in {"number", "integer"}:
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "array":
        return "Array<" + render(schema.get("items", {}), prefix) + ">"
    if kind == "object" or "properties" in schema:
        props = schema.get("properties", {})
        required = schema.get("required", [])
        fields = [
            json.dumps(key)
            + ("" if key in required else "?")
            + ": "
            + render(value, prefix)
            for key, value in props.items()
        ]
        additional = schema.get("additionalProperties", False if props else True)
        suffix = ""
        if additional is not False:
            value = (
                render(additional, prefix)
                if isinstance(additional, dict)
                else "unknown"
            )
            suffix = "Record<string, " + value + ">"
        body = "{ " + "; ".join(fields) + " }" if fields else ""
        return (
            " & ".join(part for part in [body, suffix] if part)
            or "Record<string, never>"
        )
    return "unknown"



def declarations(models, source):
    rows = ["// Generated by " + source + ". Edit the Python contracts.", ""]
    for name, model in models.items():
        schema = model.model_json_schema()
        for key, body in sorted(schema.get("$defs", {}).items()):
            rows.append("export type " + name + "_" + key + " = " + render(body, name) + ";")
        rows.extend(["export type " + name + " = " + render(schema, name) + ";", ""])
    return "\n".join(rows)
