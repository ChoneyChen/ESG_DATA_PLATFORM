#!/usr/bin/env python3
"""Export Console's data types from authoritative Python contracts."""

from pathlib import Path
import argparse, json, sys

ROOT = Path(__file__).resolve().parents[1] / "ExtractESG"
sys.path.insert(0, str(ROOT.parent / "ClauseESG/src"))
sys.path.insert(0, str(ROOT / "contracts/src"))
sys.path.insert(0, str(ROOT.parent / "ConsoleESG/backend/src"))
sys.path.insert(0, str(ROOT.parent / "database/src"))
sys.path.insert(0, str(ROOT.parent / "tools"))
from contract_types import render
from esg_console.monitor import MonitorSnapshot
from esg_console.products import SessionProducts
from esg_clauses.contract import ClauseContract
from esg_clauses.descriptor import ClauseRecord, ClauseDescriptor
from esg_clauses.catalog import ClauseCatalog, ClauseGroup
from esg_reports.contract import (
    ReportResource,
    ReportList,
    BatchManifest,
    ReportImportResult,
    ReportUploadResult,
)
from esg_contracts.facts import (
    SourceFact,
    RunRequest,
    PipelineBudget,
    ClauseCoverage,
    ClauseMapping,
)
from esg_data.organization import OrganizedDataset, OrganizationSpec
from esg_contracts.evidence import DocumentReference, EvidenceStructure, ObjectSearchPage
from esg_data.periods import ReportedPeriod
from esg_contracts.results import FactCollection, FactBundle, CandidateRejection
from esg_contracts.operations import TaskObservation
from esg_contracts.sessions import ExtractionPlanRequest, ExtractionSession, NativeRun

MODELS = {
    "ReportedPeriod": ReportedPeriod,
    "EvidenceStructure": EvidenceStructure,
    "ObjectSearchPage": ObjectSearchPage,
    "CandidateRejection": CandidateRejection,
    "MonitorSnapshot": MonitorSnapshot,
    "SessionProducts": SessionProducts,
    "FactCollection": FactCollection,
    "FactBundle": FactBundle,
    "TaskObservation": TaskObservation,
    "Clause": ClauseContract,
    "ClauseRecord": ClauseRecord,
    "ClauseDescriptor": ClauseDescriptor,
    "ClauseCatalog": ClauseCatalog,
    "ClauseGroup": ClauseGroup,
    "ReportResource": ReportResource,
    "ReportList": ReportList,
    "ReportBatch": BatchManifest,
    "CreateExtraction": ExtractionPlanRequest,
    "ExtractionSession": ExtractionSession,
    "NativeRun": NativeRun,
    "ReportImportResult": ReportImportResult,
    "ReportUploadResult": ReportUploadResult,
    "SourceFact": SourceFact,
    "ExtractionRequest": RunRequest,
    "ExtractionBudget": PipelineBudget,
    "ClauseCoverage": ClauseCoverage,
    "ClauseMapping": ClauseMapping,
    "OrganizedDataset": OrganizedDataset,
    "OrganizationSpec": OrganizationSpec,
    "DocumentReference": DocumentReference,
}



def generate():
    rows = [
        "// Generated by tools/export_console_types.py. Edit the Python contracts.",
        "",
    ]
    for name, model in MODELS.items():
        schema = model.model_json_schema()
        for key, body in sorted(schema.get("$defs", {}).items()):
            rows.append(
                "export type " + name + "_" + key + " = " + render(body, name) + ";"
            )
        rows.extend(["export type " + name + " = " + render(schema, name) + ";", ""])
    rows.append("export const EXTRACTION_BUDGET_DEFAULTS: ExtractionBudget = " + json.dumps(PipelineBudget().model_dump()) + ";")
    limits = {key: {bound: value[bound] for bound in ("minimum", "maximum")} for key, value in PipelineBudget.model_json_schema()["properties"].items()}
    rows.append("export const EXTRACTION_BUDGET_LIMITS = " + json.dumps(limits) + " as const;")
    return "\n".join(rows)


def check(write=False):
    path = ROOT.parent / "ConsoleESG/frontend/src/shared/contracts.ts"
    body = generate()
    if write:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(body, encoding="utf-8")
    elif not path.is_file() or path.read_text() != body:
        raise SystemExit("Console contract types differ; export them explicitly")
    return {"models": len(MODELS), "target": str(path.relative_to(ROOT.parent))}


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    print(json.dumps(check(args.write), ensure_ascii=False))
